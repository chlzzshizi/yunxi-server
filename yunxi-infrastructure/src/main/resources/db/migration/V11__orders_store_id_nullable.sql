-- 网单的归属门店改为可选（2026-09-13 口径变更）
--
-- 原口径：网单的 store_id 是顾客在下单页挑的，必须存在且营业中（§6.4）。
-- 新口径：顾客**可以不选**。理由是它跟 §4.4 已经写下的一句话本来就别扭 ——
--   "网单顾客在线注册，没有门店归属，customers.store_id 为 NULL" ——
-- 顾客自己没有门店归属，却必须替订单挑一家店，说不通。
--
-- 列是 V1 建的 NOT NULL，"不选"就无处安放，所以放开它。
-- 门店不做数据隔离（§4.2：所有店长可管理所有订单），NULL 因此不影响任何权限判断，
-- 只是让"这张网单没有归属门店"成为一句存得下来的事实。
--
-- 门店单不受影响：它的 store_id 取自店长 token，永远有值。
ALTER TABLE orders
    MODIFY COLUMN store_id BIGINT DEFAULT NULL
        COMMENT '归属门店；门店单=店长所在店，网单=顾客指定（可不指定，则为 NULL）';
