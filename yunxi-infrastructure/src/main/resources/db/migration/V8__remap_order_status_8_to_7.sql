-- ============================================
-- V8__remap_order_status_8_to_7.sql
-- 状态机连号（2026-09-11）：原「8 已取件」并进「7 已完成」，7 成为通用终态
--
-- 为什么必须迁移而不能放着不管：
--   orders.status 存的是**码值**（tinyint），读出时走 OrderStatus.fromCode()。
--   新枚举里没有 8 了，历史行的 8 会在订单列表/详情里直接抛
--   IllegalArgumentException("没有这个状态:8") → 整页 500，而且这单永远打不开。
--
-- 为什么可以直接 UPDATE：8 和 7 在新口径下是**同一个业务含义**（衣服已交付顾客、
-- 订单结束），只是旧模型多插了一格"已送达"的物流态。语义上没有信息损失。
--
-- 与 V7 一样属于"老概念的清尾"，所以放在同一批迁移里。
-- ============================================

UPDATE orders SET status = 7 WHERE status = 8;
